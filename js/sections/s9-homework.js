/* Блок 9. Домашнее задание: по одной-две задачи на каждую тему маршрута. */
(function () {
  "use strict";
  var h = UI.h, m = UI.m;

  var DZ_PTS = [[-6, 2], [-3, -2], [1, 4], [4, -1], [6, 1]];
  var dz = UI.smooth(DZ_PTS);
  function dzPlot() {
    return { x: [-7, 7], y: [-3, 5], unitGrid: true, layers: [
      { type: "fn", f: dz, color: "#d18f00", domain: [-6, 6] },
      { type: "point", x: -6, y: 2, color: "#d18f00", r: 5 },
      { type: "point", x: 6, y: 1, color: "#d18f00", r: 5 }] };
  }
  function pair(x, y, hint) {
    return function (v) {
      var a = UI.parseNumbers(v);
      if (a.length !== 2 || a.some(isNaN)) return "Нужно два числа: x; y";
      if (Math.abs(a[0] - x) < 1e-6 && Math.abs(a[1] - y) < 1e-6) return true;
      if (Math.abs(a[0] - y) < 1e-6 && Math.abs(a[1] - x) < 1e-6) return "Числа верные, но порядок другой: сначала x, потом y";
      return hint && Math.abs(a[0] - x) < 1e-6 ? hint : false;
    };
  }

  App.register({
    id: "hw", num: 9, color: "var(--green)", tasks: 12,
    title: "Домашнее задание", subtitle: "12 задач: по одной-две на каждую тему",
    render: function (root) {
      var s0 = UI.section("Как делать домашку");
      s0.appendChild(UI.theory("<p>Решай в тетради, а сюда вводи только ответ. Над каждой задачей написано, к какой теме она относится: если застрял, вернись в этот блок маршрута и перечитай теорию.</p>"));
      s0.appendChild(UI.callout("tip", "<p>Кнопка «Решение» появляется после двух неверных ответов. Если открыл решение до того, как решил сам, получишь только половину XP. Так что сначала — подсказки.</p>"));
      root.appendChild(s0);

      var s1 = UI.section("Задачи");
      var t = h("div", { class: "tasks" });
      t.appendChild(UI.task({
        id: "hw:t1", level: 1, xp: 10, kind: "number", badge: "Тема 1 · функция",
        q: "<p>" + m("f(x)=-2x^2+3x") + ". Найди " + m("f(-1)") + ".</p>", answer: -5,
        hints: ["(−1)² = 1, поэтому −2·(−1)² = −2. А 3·(−1) = −3."],
        solution: "f(−1) = −2·1 + 3·(−1) = −2 − 3 = −5."
      }));
      t.appendChild(UI.task({
        id: "hw:t2", level: 2, xp: 15, kind: "numbers", badge: "Тема 1 · функция",
        q: "<p>При каких x функция " + m("y=5/(x^2-9)") + " не определена? Перечисли все.</p>", answer: [-3, 3],
        hints: ["На ноль делить нельзя: x² − 9 = 0."],
        solution: "x² − 9 = 0 → x² = 9 → x = 3 или x = −3. Область определения: все x, кроме ±3."
      }));
      t.appendChild(UI.task({
        id: "hw:t3", level: 1, xp: 10, kind: "number", badge: "Тема 2 · график", prefix: "x =",
        q: "<p>Найди абсциссу точки пересечения графиков " + m("y=3x-4") + " и " + m("y=-x+8") + ".</p>", answer: 3,
        hints: ["Приравняй правые части: 3x − 4 = −x + 8."],
        solution: "3x − 4 = −x + 8 → 4x = 12 → x = 3. Сама точка — (3; 5)."
      }));
      t.appendChild(UI.task({
        id: "hw:t4", level: 1, xp: 10, kind: "numbers", badge: "Тема 3 · свойства",
        q: "<p>Найди нули функции " + m("y=(x+4)(2x-6)") + ".</p>", answer: [-4, 3],
        hints: ["Произведение равно нулю, когда хотя бы один множитель равен нулю."],
        solution: "x + 4 = 0 → x = −4; 2x − 6 = 0 → x = 3."
      }));
      t.appendChild(UI.task({
        id: "hw:t5", level: 2, xp: 15, kind: "choice", badge: "Тема 3 · свойства", plot: dzPlot(),
        q: "<p>На рисунке график функции y = f(x), заданной на отрезке [−6; 6]. Найди промежутки <b>убывания</b>.</p>",
        options: ["[−6; −3] и [1; 4]", "[−3; 1] и [4; 6]", "[−2; 4]", "(−6; 1)"], answer: 0,
        hints: ["Иди слева направо и отмечай, где график идёт вниз. Записывай концы по оси x."],
        solution: "С горки график идёт от x = −6 до x = −3 и от x = 1 до x = 4. Ответ [−6; −3] и [1; 4]."
      }));
      t.appendChild(UI.task({
        id: "hw:t6", level: 1, xp: 10, kind: "number", badge: "Тема 3 · свойства", plot: dzPlot(),
        q: "<p>По тому же графику найди наименьшее значение функции.</p>", answer: -2,
        hints: ["Значение — это y. Найди самую низкую точку графика."],
        solution: "Самая низкая точка (−3; −2). Наименьшее значение −2. Ответ «−3» — это x, а не значение."
      }));
      t.appendChild(UI.task({
        id: "hw:t7", level: 2, xp: 15, kind: "choice", badge: "Тема 3 · свойства", plot: dzPlot(),
        q: "<p>По тому же графику найди область значений " + m("E(f)") + ".</p>",
        options: ["[−2; 4]", "[−6; 6]", "(−2; 4)", "[1; 4]"], answer: 0,
        hints: ["Область значений — от самой низкой высоты до самой высокой. Все промежуточные высоты график проходит."],
        solution: "Самая низкая точка на высоте −2, самая высокая — на высоте 4, обе на графике. E(f) = [−2; 4]. А [−6; 6] — это D(f)."
      }));
      t.appendChild(UI.task({
        id: "hw:t8", level: 2, xp: 15, kind: "choice", badge: "Тема 3 · свойства",
        q: "<p>Какие из функций чётные? Отметь вариант, где перечислены все чётные и только они.</p><p>1) " + m("y=x^4-2x^2") + "&nbsp;&nbsp; 2) " + m("y=x^3-x") + "&nbsp;&nbsp; 3) " + m("y=|x|+1") + "&nbsp;&nbsp; 4) " + m("y=(x+1)^2") + "</p>",
        options: ["1 и 3", "1, 3 и 4", "только 1", "2 и 4"], answer: 0,
        hints: ["Подставь −x вместо x в каждую формулу. Если формула не изменилась — чётная."],
        solution: "1) (−x)⁴ − 2(−x)² = x⁴ − 2x² — чётная. 2) нечётная: знак меняется. 3) |−x| + 1 = |x| + 1 — чётная. 4) (−x + 1)² = (x − 1)² ≠ (x + 1)² — ни то ни другое: её график симметричен относительно x = −1, а не оси y."
      }));
      t.appendChild(UI.task({
        id: "hw:t9", level: 1, xp: 10, kind: "number", badge: "Тема 4 · зоопарк", prefix: "k =",
        q: "<p>Гипербола " + m("y=k/x") + " проходит через точку (−3; −4). Найди k.</p>", answer: 12,
        hints: ["k = x·y."],
        solution: "k = (−3)·(−4) = 12. Ветви в I и III четвертях."
      }));
      t.appendChild(UI.task({
        id: "hw:t10", level: 1, xp: 10, kind: "formula", badge: "Тема 5 · сдвиги", prefix: "y =",
        q: "<p>График " + m("y=|x|") + " сдвинули на 3 вправо и на 2 вверх. Запиши формулу.</p>", answer: "|x-3|+2",
        hints: ["Вправо — минус внутри модуля. Вверх — плюс снаружи."],
        solution: "y = |x − 3| + 2. Угол галочки — в точке (3; 2)."
      }));
      t.appendChild(UI.task({
        id: "hw:t11", level: 2, xp: 15, kind: "numbers", badge: "Тема 6 · парабола",
        q: "<p>Найди координаты вершины параболы " + m("y=-x^2+4x-1") + ". Через точку с запятой: x; y.</p>",
        check: pair(2, 3, "x₀ верный! Теперь подставь его в формулу, чтобы найти y₀"),
        hints: ["x₀ = −b / (2a) = −4 / (−2).", "y₀ = −2² + 4·2 − 1."],
        solution: "x₀ = −4 / (2·(−1)) = 2. y₀ = −4 + 8 − 1 = 3. Вершина (2; 3)."
      }));
      t.appendChild(UI.task({
        id: "hw:t12", level: 2, xp: 15, kind: "choice", badge: "Тема 6 · парабола",
        q: "<p>Найди область значений функции " + m("y=x^2-6x+10") + ".</p>",
        options: ["[1; +∞)", "[3; +∞)", "(−∞; 1]", "[10; +∞)"], answer: 0,
        hints: ["Ветви вверх, значит область значений — от вершины и выше. Найди y₀."],
        solution: "x₀ = 6 / 2 = 3, y₀ = 9 − 18 + 10 = 1. E = [1; +∞). Ответ [3; +∞) — ловушка: 3 — это x вершины."
      }));
      s1.appendChild(t);
      root.appendChild(s1);
    }
  });
})();
