/* Блок 7. Босс-задачи: формат второй части ОГЭ, с интерактивным «щупом». */
(function () {
  "use strict";
  var h = UI.h, m = UI.m;

  var countCommon = UI.countCommon, hProbe = UI.hProbe;

  App.register({
    id: "boss", num: 7, color: "#e04848", tasks: 10,
    title: "Босс-задачи", subtitle: "Вторая часть ОГЭ: строим, двигаем, считаем",
    render: function (root) {
      var s0 = UI.section("Как побеждать боссов");
      s0.appendChild(UI.theory(
        "<p>Задача 22 в ОГЭ почти всегда звучит так: «Постройте график функции. Определите, при каких значениях m прямая y = m имеет с графиком ровно N общих точек».</p>" +
        "<p>Секрет простой: <b>прямая y = m — горизонтальная линейка</b>. Её возят вверх-вниз и считают пересечения. Количество меняется только в особых местах: на вершинах, углах, концах кусков и выколотых точках. Их и надо найти.</p>"));
      s0.appendChild(UI.callout("tip", "<p>Ниже у задач с графиком есть такая линейка — её можно потаскать. На экзамене её не будет, поэтому после каждой задачи проговори, <i>почему</i> получилось именно так.</p>"));
      root.appendChild(s0);

      var t = h("div", { class: "tasks" });

      var f1 = function (x) { return x * x - 4 * Math.abs(x) + 3; };
      t.appendChild(UI.task({
        id: "boss:b1", level: 2, xp: 30, kind: "number", prefix: "m =", badge: "Босс 1",
        q: "<p>Функция " + m("y=x^2-4|x|+3") + ". При каком m прямая y = m имеет с графиком <b>ровно три</b> общие точки?</p>",
        extra: hProbe(f1, { x: [-6, 6], y: [-2.5, 6], start: 0 }),
        answer: 3,
        hints: ["При x ≥ 0 это x² − 4x + 3 — парабола с вершиной (2; −1). Функция чётная, поэтому левая часть — зеркальная копия.", "Получилось две «ямки» с горбом между ними. Где прямая коснётся горба?"],
        solution: "При x ≥ 0: y = (x − 2)² − 1, вершина (2; −1); слева — зеркально. Между ямками горб с вершиной (0; 3). Прямая y = 3 проходит через вершину горба и ещё по разу через каждую ветку — ровно три точки."
      }));

      var f2 = function (x) { return Math.abs(x * x - 4 * x); };
      t.appendChild(UI.task({
        id: "boss:b2", level: 2, xp: 30, kind: "number", prefix: "m =", badge: "Босс 2",
        q: "<p>Функция " + m("y=|x^2-4x|") + ". При каком m прямая y = m имеет с графиком ровно три общие точки?</p>",
        extra: hProbe(f2, { x: [-2, 6], y: [-1.5, 7], start: 2 }),
        answer: 4,
        hints: ["Построй y = x² − 4x (вершина (2; −4)), а потом всё, что ниже оси x, отрази вверх — так работает модуль снаружи.", "Отражённая вершина окажется в (2; 4)."],
        solution: "Кусок параболы между нулями 0 и 4 отражается вверх и превращается в горб с вершиной (2; 4). Прямая y = 4 касается горба и пересекает две внешние ветки — три точки."
      }));

      var f3 = function (x) { return x === 2 ? NaN : (x * x - 4) / (x - 2); };
      var kNow = 0.5;
      var pb3 = UI.plotBox({ x: [-6, 6], y: [-4, 7], unitGrid: true });
      var read3 = h("div", { class: "stat" });
      function draw3() {
        pb3.plot.layers = [
          { type: "fn", f: f3, color: "#d18f00", width: 3.5 },
          { type: "point", x: 2, y: 4, open: true, color: "#d18f00", r: 6 },
          { type: "fn", f: function (x) { return kNow * x; }, color: "#0a8bd0", width: 2.5 }
        ];
        pb3.plot.draw();
        read3.innerHTML = "k = <b>" + UI.fmt(kNow) + "</b> · общих точек: <b>" + countCommon(f3, function (x) { return kNow * x; }, -6, 6) + "</b>";
      }
      UI.later(function () { pb3.mount(); draw3(); });
      t.appendChild(UI.task({
        id: "boss:b3", level: 3, xp: 40, kind: "numbers", badge: "Босс 3",
        q: "<p>Функция " + m("y=(x^2-4)/(x-2)") + ". При каких k прямая y = kx <b>не имеет</b> с графиком общих точек? Перечисли все такие k.</p>",
        extra: h("div", { class: "sliders" }, pb3.el,
          UI.slider("k", -3, 4, 0.25, kNow, function (v) { kNow = v; draw3(); }, { color: "cyan" }), read3),
        answer: [1, 2],
        hints: ["Сократи дробь: x² − 4 = (x − 2)(x + 2). Но помни, что при x = 2 функция не определена — на графике дырка.", "Прямая y = kx вращается вокруг (0; 0). Не пересечёт график, если пойдёт параллельно ему… или попадёт ровно в дырку."],
        solution: "y = x + 2 при x ≠ 2, в точке (2; 4) выколота дырка. Прямая y = kx не имеет общих точек в двух случаях. Первый — параллельна: k = 1. Второй — проходит через дырку: 4 = 2k, k = 2. Ответ: 1 и 2."
      }));

      var f4 = function (x) { return x < -1 ? x + 3 : x * x + 1; };
      t.appendChild(UI.task({
        id: "boss:b4", level: 3, xp: 40, kind: "choice", badge: "Босс 4",
        q: "<p>Функция задана кусками: " + m("y=x+3") + " при x < −1 и " + m("y=x^2+1") + " при x ≥ −1. При каких m прямая y = m имеет с графиком ровно три общие точки?</p>",
        extra: hProbe(f4, { x: [-6, 4], y: [-2, 6], start: 0.5 }),
        options: ["(1; 2)", "[1; 2]", "(1; 2]", "m = 1 и m = 2"], answer: 0,
        hints: ["Посмотри внимательно на концы: что происходит ровно при m = 1 и ровно при m = 2?", "При m = 2 прямая проходит через стык кусков (−1; 2). Сколько там точек — одна или две?"],
        solution: "Три точки получаются, когда прямая выше вершины (0; 1) и ниже стыка (−1; 2): одна на прямом куске и две на параболе. При m = 1 касание вершины — всего 2 точки. При m = 2 стык считается один раз, плюс точка (1; 2) — снова 2. Ответ (1; 2), концы не входят."
      }));

      t.appendChild(UI.task({
        id: "boss:b5", level: 2, xp: 25, kind: "formula", prefix: "y =", badge: "Босс 5",
        q: "<p>Запиши формулу параболы по графику.</p>", answer: "-0.5(x+1)^2+4",
        plot: { x: [-6, 5], y: [-4, 5.5], unitGrid: true, layers: [
          { type: "fn", f: function (x) { return -0.5 * (x + 1) * (x + 1) + 4; }, color: "#e23468" },
          { type: "point", x: -1, y: 4, color: "#1d2033" }, { type: "point", x: 1, y: 2, color: "#1d2033" }] },
        hints: ["Вершина даёт сдвиги: y = a(x − x₀)² + y₀.", "Чтобы найти a, отойди от вершины на 1 вправо, а лучше на 2: при шаге 2 у y = x² подъём 4. Здесь — спуск на 2."],
        solution: "Вершина (−1; 4): y = a(x + 1)² + 4. Подставим отмеченную точку (1; 2): 2 = a·4 + 4 → a = −0,5. Ответ: y = −0,5(x + 1)² + 4."
      }));

      t.appendChild(UI.task({
        id: "boss:b6", level: 2, xp: 25, kind: "formula", prefix: "y =", badge: "Босс 6",
        q: "<p>Прямая проходит через точки (−2; 5) и (4; −1). Запиши её формулу.</p>", answer: "-x+3",
        hints: ["k = (−1 − 5) / (4 − (−2)).", "Нашёл k — подставь одну из точек в y = kx + b, чтобы найти b."],
        solution: "k = −6 / 6 = −1. 5 = −1·(−2) + b → b = 3. y = −x + 3."
      }));

      t.appendChild(UI.task({
        id: "boss:b7", level: 3, xp: 30, kind: "numbers", badge: "Босс 7",
        q: "<p>При каких p вершина параболы " + m("y=x^2-px+9") + " лежит на оси x?</p>", answer: [-6, 6],
        hints: ["Вершина на оси x — значит, парабола касается оси и у уравнения один корень."],
        solution: "Нужно D = 0: p² − 36 = 0 → p = 6 или p = −6. Проверка: x² − 6x + 9 = (x − 3)², x² + 6x + 9 = (x + 3)²."
      }));

      t.appendChild(UI.task({
        id: "boss:b8", level: 2, xp: 25, kind: "numbers", badge: "Босс 8",
        q: "<p>Найди абсциссы точек пересечения графиков " + m("y=6/x") + " и " + m("y=-x+5") + ".</p>", answer: [2, 3],
        hints: ["6/x = −x + 5. Умножь на x и собери квадратное уравнение."],
        solution: "6 = −x² + 5x → x² − 5x + 6 = 0 → x = 2 или x = 3. Точки (2; 3) и (3; 2)."
      }));

      t.appendChild(UI.task({
        id: "boss:b9", level: 3, xp: 30, kind: "choice", badge: "Босс 9",
        q: "<p>Функция f чётная и возрастает при x ≥ 0. Что больше: " + m("f(2)") + " или " + m("f(-4)") + "?</p>",
        options: [m("f(2)>f(-4)"), m("f(2)<f(-4)"), "Они равны", "Нельзя определить"], answer: 1,
        hints: ["Чётная — значит f(−4) = f(4).", "Теперь сравни f(2) и f(4), зная, что справа функция растёт."],
        solution: "f(−4) = f(4) по чётности. При x ≥ 0 функция растёт, а 2 < 4, значит f(2) < f(4) = f(−4)."
      }));

      t.appendChild(UI.task({
        id: "boss:b10", level: 3, xp: 30, kind: "number", badge: "Финальный босс",
        q: "<p>График " + m("y=x^2+bx+c") + " получен из " + m("y=x^2") + " сдвигом на 3 вправо и на 1 вниз. Найди b + c.</p>", answer: 2,
        hints: ["Запиши формулу через сдвиги, потом раскрой скобки."],
        solution: "y = (x − 3)² − 1 = x² − 6x + 9 − 1 = x² − 6x + 8. b = −6, c = 8, b + c = 2."
      }));

      var s1 = UI.section("Боссы");
      s1.appendChild(t);
      root.appendChild(s1);
    }
  });
})();
